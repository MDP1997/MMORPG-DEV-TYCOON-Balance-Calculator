export function t(key) {
  const lang = state.lang === "es" ? "es" : "en";
  return dict[lang]?.[key] ?? key;
}

export function applyLanguage(root = document) {
  const nodes = root.querySelectorAll("[data-i18n]");
  nodes.forEach((el) => {
    const k = el.getAttribute("data-i18n");
    el.textContent = t(k);
  });
}
